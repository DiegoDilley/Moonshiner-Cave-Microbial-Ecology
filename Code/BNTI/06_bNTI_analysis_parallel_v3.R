# =============================================================================
# bMNTD / bMTI / RCbray — Stegen et al. 2012/2013 Framework
# OSC Pitzer version — Parallelized
# Version 3 — Full corrected pipeline
#
# CHANGE FROM v2:
#   RCbray null model read distribution fixed to match Stegen 2013
#   Supplementary Methods exactly. In v2, reads were distributed across
#   chosen OTUs with equal probability (rep(1/obs_rich, obs_rich)).
#   Stegen 2013 Supp. states: "the probability of drawing an individual
#   into a given species is proportional to that species abundance in the
#   meta-community." v3 corrects this by weighting the rmultinom draw
#   by regional_weight (occ_freq x mean_relab), renormalized to the
#   chosen OTUs only (Step B of RCbray null, see Step 5 below).
#
# FRAMEWORK OVERVIEW (Stegen et al. 2012, 2013):
#   Step 1: Calculate observed bMNTD (abundance-weighted phylogenetic
#           distance between closest relatives across community pairs).
#   Step 2: Compare to null (tip-shuffled) bMNTD to get bMTI.
#           |bMTI| > 2 --> Selection governs turnover.
#   Step 3: For pairs where |bMTI| < 2, calculate RCbray.
#           RCbray > +0.95  --> Dispersal Limitation + Drift
#           RCbray < -0.95  --> Homogenizing Dispersal
#           |RCbray| <= 0.95 --> Drift alone
#
# REFERENCES:
#   Stegen et al. 2012. ISME J 6:1653-1664.
#   Stegen et al. 2013. ISME J 7:2069-2079.
#   Chase et al. 2011. Ecosphere 2:art24.
# =============================================================================

.libPaths("/users/PAS2933/diegodilley/BNTI/rlib")

library(phyloseq)
library(picante)
library(vegan)
library(dplyr)
library(foreach)
library(doParallel)

setwd("/users/PAS2933/diegodilley/BNTI")
if (!dir.exists("Outputs")) dir.create("Outputs", recursive = TRUE)

# =============================================================================
# STEP 0 — SET UP PARALLEL BACKEND
# =============================================================================

n_cores <- as.integer(Sys.getenv("SLURM_CPUS_PER_TASK", unset = 1))
cat("Cores available:", n_cores, "\n")

cl <- makeCluster(n_cores)
registerDoParallel(cl)
cat("Parallel backend registered with", n_cores, "cores\n\n")

# =============================================================================
# STEP 1 — LOAD DATA
# =============================================================================

cat("Loading phyloseq object...\n")
phy <- readRDS("Inputs/phyloseq_filtered_counts_DNA_tree.rds")

otu  <- as.matrix(t(otu_table(phy)))
tree <- phy_tree(phy)
meta <- as.data.frame(sample_data(phy))

cat("Samples:", nrow(otu), "\n")
cat("Taxa:   ", ncol(otu), "\n")
cat("Tree tips:", length(tree$tip.label), "\n")
cat("Tree rooted:", is.rooted(tree), "\n")
stopifnot(all(colnames(otu) %in% tree$tip.label))
cat("Tree/OTU match: OK\n")

n_reps <- 999
n_samp <- nrow(otu)

# =============================================================================
# STEP 2 — OBSERVED bMNTD
#
# Abundance-weighted mean phylogenetic distance between each OTU in one
# community and its closest relative in a second community.
# Calculated using picante::comdistnt with abundance.weighted = TRUE.
# Following Stegen et al. 2012.
# =============================================================================

cat("\nCalculating observed bMNTD...\n")

bMNTD_obs <- comdistnt(
  comm               = otu,
  dis                = cophenetic(tree),
  abundance.weighted = TRUE
)

bMNTD_obs_mat <- as.matrix(bMNTD_obs)
cat("bMNTD matrix dimensions:", dim(bMNTD_obs_mat), "\n")

# =============================================================================
# STEP 3 — bMNTD NULL MODEL (parallelized)
#
# Null expectation generated by shuffling tip labels on the phylogeny 999
# times, recalculating bMNTD each time. Community compositions (OTU
# abundances) are held constant; only phylogenetic positions are randomized.
# Following Stegen et al. 2012.
# =============================================================================

cat("\nRunning", n_reps, "bMNTD null randomizations across", n_cores, "cores...\n")
t_start <- proc.time()

set.seed(42)
null_list_bMNTD <- foreach(
  i         = seq_len(n_reps),
  .packages = c("picante")
) %dopar% {
  shuffled_tree           <- tree
  shuffled_tree$tip.label <- sample(tree$tip.label)
  as.matrix(comdistnt(
    comm               = otu,
    dis                = cophenetic(shuffled_tree),
    abundance.weighted = TRUE
  ))
}

null_array <- array(
  data     = unlist(null_list_bMNTD),
  dim      = c(n_samp, n_samp, n_reps),
  dimnames = list(rownames(otu), rownames(otu), NULL)
)
rm(null_list_bMNTD)

t_elapsed <- round((proc.time() - t_start)["elapsed"] / 60, 1)
cat("bMNTD null complete in", t_elapsed, "minutes. Saving...\n")
saveRDS(null_array, "Outputs/null_bMNTD_array.rds")

# =============================================================================
# STEP 4 — bMTI
#
# bMTI = (observed bMNTD - mean(null bMNTD)) / sd(null bMNTD)
# Values > +2 or < -2 indicate significant departure from null expectation,
# interpreted as Selection governing phylogenetic turnover.
# bMTI > +2: Variable Selection (divergent environments)
# bMTI < -2: Homogeneous Selection (convergent environments)
# =============================================================================

cat("Calculating bMTI...\n")

null_mean <- apply(null_array, c(1, 2), mean, na.rm = TRUE)
null_sd   <- apply(null_array, c(1, 2), sd,   na.rm = TRUE)
bMTI_mat  <- (bMNTD_obs_mat - null_mean) / null_sd

rm(null_array)
gc()

# =============================================================================
# STEP 5 — RCbray NULL MODEL (parallelized)
#
# Applied only to pairs where |bMTI| < 2 (non-Selection governed pairs).
# Null communities assembled following Stegen 2013 Supplementary Methods,
# which extends Chase et al. 2011 Raup-Crick to account for relative
# abundances via a two-step procedure:
#
#   Step A — OTU selection:
#     Draw obs_rich OTUs without replacement from the regional pool.
#     Probability proportional to regional_weight (occ_freq x mean_relab).
#     Observed species richness is held constant per sample.
#
#   Step B — Read distribution (FIXED in v3):
#     Draw total_reads individuals into the chosen OTUs.
#     Probability proportional to regional_weight of chosen OTUs,
#     renormalized to sum to 1 across chosen OTUs only.
#     Stegen 2013 Supp.: "probability of drawing an individual into a
#     given species is proportional to that species abundance in the
#     meta-community."
#     v2 incorrectly used equal weights; v3 corrects this.
#
# Observed total read count is held constant per sample.
# =============================================================================

cat("\nBuilding regional OTU weights for RCbray null...\n")

otu_relab       <- otu / rowSums(otu)
occ_freq        <- colSums(otu > 0)
mean_relab      <- colMeans(otu_relab)
regional_weight <- occ_freq * mean_relab
regional_weight <- regional_weight / sum(regional_weight)

cat("Non-zero weighted OTUs:", sum(regional_weight > 0),
    "of", length(regional_weight), "\n")

BC_obs <- as.matrix(vegdist(otu, method = "bray"))

cat("\nRunning", n_reps, "RCbray null randomizations across", n_cores, "cores...\n")
t_start2 <- proc.time()

set.seed(43)
null_list_BC <- foreach(
  i         = seq_len(n_reps),
  .packages = c("vegan")
) %dopar% {

  null_comm <- matrix(0, nrow = n_samp, ncol = ncol(otu),
                      dimnames = list(rownames(otu), colnames(otu)))

  for (s in seq_len(n_samp)) {

    total_reads <- sum(otu[s, ])
    obs_rich    <- sum(otu[s, ] > 0)

    # Step A: select OTUs weighted by regional occurrence x abundance
    chosen_otus <- sample(
      x       = colnames(otu),
      size    = obs_rich,
      replace = FALSE,
      prob    = regional_weight
    )

    # Step B (FIXED): distribute reads weighted by regional abundance,
    # renormalized to chosen OTUs only
    chosen_weights            <- regional_weight[chosen_otus]
    chosen_weights            <- chosen_weights / sum(chosen_weights)
    read_counts               <- rmultinom(1,
                                           size = total_reads,
                                           prob = chosen_weights)[, 1]
    null_comm[s, chosen_otus] <- read_counts
  }

  as.matrix(vegdist(null_comm, method = "bray"))
}

null_BC_array <- array(
  data     = unlist(null_list_BC),
  dim      = c(n_samp, n_samp, n_reps),
  dimnames = list(rownames(otu), rownames(otu), NULL)
)
rm(null_list_BC)

t_elapsed2 <- round((proc.time() - t_start2)["elapsed"] / 60, 1)
cat("RCbray null complete in", t_elapsed2, "minutes. Saving...\n")
saveRDS(null_BC_array, "Outputs/null_BC_array.rds")

# RCbray = 2 * P(null BC >= observed BC) - 1
# Scaled to [-1, +1] following Chase et al. 2011 / Stegen et al. 2013
cat("Calculating RCbray scores...\n")

RCbray_mat <- matrix(NA, nrow = n_samp, ncol = n_samp,
                     dimnames = list(rownames(otu), rownames(otu)))

for (r in seq_len(n_samp)) {
  for (cc in seq_len(n_samp)) {
    if (r == cc) next
    obs_val           <- BC_obs[r, cc]
    null_vals         <- null_BC_array[r, cc, ]
    prop_ge           <- mean(null_vals >= obs_val, na.rm = TRUE)
    RCbray_mat[r, cc] <- 2 * prop_ge - 1
  }
}

rm(null_BC_array)
gc()

# =============================================================================
# STEP 6 — PROCESS CLASSIFICATION (Stegen 2013 Figure 3)
#
# Two-step decision framework applied to all pairwise community comparisons:
#
#   Step 1 — bMTI:
#     |bMTI| > 2  --> Selection (skip RCbray for this pair)
#       bMTI > +2 --> Variable Selection
#       bMTI < -2 --> Homogeneous Selection
#
#   Step 2 — RCbray (only for pairs where |bMTI| <= 2):
#     RCbray > +0.95  --> Dispersal Limitation + Drift
#     RCbray < -0.95  --> Homogenizing Dispersal
#     |RCbray| <= 0.95 --> Drift (undominated)
# =============================================================================

cat("Classifying ecological processes...\n")

samp_names   <- rownames(otu)
results_list <- list()

for (r in seq_len(n_samp - 1)) {
  for (cc in (r + 1):n_samp) {

    s1           <- samp_names[r]
    s2           <- samp_names[cc]
    bmtd_obs_val <- bMNTD_obs_mat[r, cc]
    bmti_val     <- bMTI_mat[r, cc]
    rc_val       <- RCbray_mat[r, cc]

    if (abs(bmti_val) > 2) {
      process <- ifelse(bmti_val > 2, "Variable_Selection", "Homogeneous_Selection")
    } else if (rc_val > 0.95) {
      process <- "Drift_Dispersal_Limitation"
    } else if (rc_val < -0.95) {
      process <- "Homogenizing_Dispersal"
    } else {
      process <- "Drift_Undominated"
    }

    type1           <- meta[s1, "Site_Type"]
    type2           <- meta[s2, "Site_Type"]
    comparison_type <- paste(sort(c(as.character(type1),
                                    as.character(type2))), collapse = "_vs_")

    results_list[[length(results_list) + 1]] <- data.frame(
      Sample1          = s1,
      Sample2          = s2,
      SiteType1        = type1,
      SiteType2        = type2,
      Comparison       = comparison_type,
      bMNTD_obs        = bmtd_obs_val,
      bMTI             = bmti_val,
      RCbray           = rc_val,
      Process          = process,
      stringsAsFactors = FALSE
    )
  }
}

results <- bind_rows(results_list)

# =============================================================================
# STEP 7 — SAVE OUTPUTS
# =============================================================================

write.csv(results,       "Outputs/bMTI_RCbray_results.csv",  row.names = FALSE)
write.csv(bMNTD_obs_mat, "Outputs/bMNTD_observed_matrix.csv")
write.csv(bMTI_mat,      "Outputs/bMTI_matrix.csv")
write.csv(RCbray_mat,    "Outputs/RCbray_matrix.csv")

cat("\n=== DONE ===\n")
cat("Total pairwise comparisons:", nrow(results), "\n\n")

process_summary <- results %>%
  count(Comparison, Process) %>%
  group_by(Comparison) %>%
  mutate(Percent = round(100 * n / sum(n), 1)) %>%
  arrange(Comparison, desc(n))

print(process_summary)
write.csv(process_summary, "Outputs/Process_Summary.csv", row.names = FALSE)

cat("\nAll outputs saved to Outputs/\n")

stopCluster(cl)
